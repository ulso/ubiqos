// The rest of what lwIP expects from a C library.
//
// Four symbols short of linking: atoi, snprintf, and newlib's _ctype_ table
// behind the isdigit family. A module is linked -nostdlib and cannot reach the
// kernel's copies, so it brings its own.

#include <stddef.h>
#include <stdint.h>
#include <stdarg.h>

int atoi(const char *s) {
    int sign = 1, v = 0;
    while (*s == ' ' || *s == '\t') s++;
    if (*s == '-') { sign = -1; s++; } else if (*s == '+') s++;
    while (*s >= '0' && *s <= '9') v = v * 10 + (*s++ - '0');
    return sign * v;
}


// A 8x16 fixed-width font covering 32..255 -- ASCII and Latin-1 -- one byte
// per scanline with the leftmost pixel in bit 7, 16 bytes per glyph. A cell
// narrower than eight pixels leaves the low bits clear.
//
// Latin-1 rather than ASCII because a keyboard layout is no use without the
// letters it produces: a Swedish one gives a, a and o with their marks, and
// there has to be something to draw.
//
// Terminus, a bitmap font drawn by hand on this exact grid. The table is baked
// into the kernel image and so inherits the typeface's licence:
//
//   Copyright (C) 2020 Dimitar Toshkov Zhekov,
//   with Reserved Font Name "Terminus Font".
//   SIL Open Font License 1.1 -- see third_party/terminus/OFL.txt
//
// This file is generated by tools/make_font.py. Edit the generator, not the
// table.
//
// IN SRAM IN CHARGEN BUILDS, AND IN FLASH OTHERWISE. That split is the whole
// fix, and it is what made it affordable -- see docs/the-board-stopped.md.
//
// The kernel is linked copy_to_ram, which pulls everything not marked
// .flashdata into SRAM "to avoid accidental flash accesses" as the SDK's
// linker script puts it. This table used to be marked, for 3584 bytes that a
// process got instead. Nothing writes flash while myrtos runs, so reading it
// looked always safe.
//
// It is not, and the accident is not a WRITE. The character generator reads
// this table from a TIMER INTERRUPT, and since 10 September the machine also
// runs driver modules whose code lives in PSRAM -- and flash and PSRAM share
// one QMI. An interrupt that lands in the middle of a PSRAM instruction fetch
// and then reads flash stalls on a bus that cannot serve it, and stays
// stalled: no fault, no crash record, the tick still counting, and the picture
// still on the screen because the DMA keeps cycling buffers nobody is
// refilling any more.
//
// That wedged the board four times in two days, and the program counter was
// sitting on `g[gy]` in chargen.c every time it was looked at.
//
// Why only chargen builds: the interrupt that reads this is chargen.c, which
// exists only there. A framebuffer build reads the same table from console.c
// in thread context, where flash is as safe as it ever was -- so it keeps the
// 3584 bytes, and kernel/font6x12.c stays in flash in every build for exactly
// the same reason. Paying only where the danger is is what brought this within
// reach of the riscv chargen build, which had nowhere near 3584 bytes spare.
//
// The rule this leaves: nothing reached from an interrupt may live in flash or
// PSRAM while modules run from PSRAM. This table was the last thing in the
// video path that did.

